import pandas as pd

# 1. Завантажуємо нашу таблицю з попереднього кроку
# Якщо файл в тій самій папці, Pandas прочитає його автоматично
df = pd.read_csv("whisper_results_cleaned.csv")

# 2. Створюємо "Ground Truth" (Еталонні дані)
# Зіставляємо назву файлу з тим звуком/складом, який реально вимовляла дитина
expected_mapping = {
    "a.wav": "а",
    "a1.wav": "а",
    "am.wav": "ам",
    "an1.wav": "ан",  
    "au.wav": "ау",
    "au1.wav": "ау",
    "m.wav": "м",
    "m1.wav": "м",
    "ma.wav": "ма",
    "ma1.wav": "ма",
    "mama.wav": "мама",
    "mama1.wav": "мама",
    "mamo.wav": "мамо",
    "mamu.wav": "маму",
    "mamu1.wav": "маму",
    "mu.wav": "му",
    "mu1.wav": "му",
    "n.wav": "н",
    "n1.wav": "н",
    "o.wav": "о",
    "o1.wav": "о",
    "r.wav": "р",
    "r1.wav": "р",
    "u.wav": "у",
    "u1.wav": "у",
    "um.wav": "ум",
    "um1.wav": "ум",
}

# Додаємо колонку "Очікуваний текст" у нашу таблицю
df["Очікуваний текст"] = df["Назва файлу"].map(expected_mapping)

# 3. Рахуємо метрику Accuracy (Точність)
# Створюємо колонку, де буде True (збіг) або False (помилка)
df["Точний збіг"] = df["Очищений текст"] == df["Очікуваний текст"]

# Рахуємо відсоток успішних розпізнавань
accuracy = df["Точний збіг"].mean() * 100

print("=== НАУКОВИЙ ЗВІТ ЕКСПЕРИМЕНТУ ===")
print(f"Загальна кількість тестів: {len(df)}")
print(f"Точність моделі Whisper 'з коробки' (Accuracy): {accuracy:.1f}%\n")

# 4. Відфільтровуємо лише помилки для подальшого аналізу
errors_df = df[df["Точний збіг"] == False]

print("=== АНАЛІЗ ПОМИЛОК ===")
print(errors_df[["Назва файлу", "Очікуваний текст", "Очищений текст"]])

# 5. Зберігаємо фінальний результат
df.to_csv("whisper_final_evaluation.csv", index=False, encoding="utf-8-sig")
print("\nДетальну таблицю з оцінками збережено у whisper_final_evaluation.csv")
